 public class Variable {
    public static void main(String[] args){

        //create //declare
        int age;
        age = 10;
        age = 20;
        System.out.println(age);

        //define or initialize
        int totalMarks = 100;
        System.out.println(totalMarks);

        //Case Sensitive
        int weight = 80;
        int WEIGHT = 90;
        System.out.println("weight:" + weight);
        System.out.println("WEIGHT:" + WEIGHT);

    }
    
}